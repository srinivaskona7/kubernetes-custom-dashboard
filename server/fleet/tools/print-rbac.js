#!/usr/bin/env node
/**
 * Print the bootstrap RBAC bundle for one cluster.
 *
 *   node server/fleet/tools/print-rbac.js > fleet-dashboard-rbac.yaml
 *
 * There is one bundle and it is read-only. The `--rollout` flag, which emitted a second
 * ClusterRole granting `patch` on workloads, is removed along with the grant itself — see the
 * note above `apply()` in onboard.js for why a dead write grant was the dangerous kind.
 *
 * The bundle is generated rather than hand-written, and `fleet-dashboard-rbac.yaml`
 * is the committed output of exactly this command. A test re-runs the generator and
 * compares, so the YAML an operator applies by hand can never quietly drift from the
 * rules the upload path applies through the API. Two ways in, one definition.
 *
 * It deliberately does not mint anything. Minting the first token is a separate, manual
 * step (`kubectl create token`) so that nothing which writes a credential is hidden
 * inside a file somebody pipes into kubectl.
 */
import YAML from 'yaml';

import onboardModule from '../onboard.js';
import { fileURLToPath } from 'node:url';
const {
  readOnlyRules,
  FLEET_NAMESPACE, FLEET_SA, CLUSTER_ROLE, SELF_MINT_ROLE
} = onboardModule;

const labels = { 'app.kubernetes.io/managed-by': 'k8s-fleet-dashboard' };

/**
 * The default object names. Every one is overridable, because a cluster's owner may have
 * a naming convention that a hardcoded `fleet-dashboard-reader` would violate — and being told
 * to rename by hand after generating is how the applied YAML drifts from what the
 * dashboard then looks for.
 *
 * `--prefix p` renames both RBAC objects together (`p-reader`, `p-token-issuer`) which is the
 * common case; the individual flags exist for the rest.
 */
function resolveNames(overrides = {}) {
  const prefix = overrides.prefix;
  const withPrefix = (value, suffix) => value || (prefix ? `${prefix}-${suffix}` : null);
  return {
    namespace: overrides.namespace || FLEET_NAMESPACE,
    serviceAccount: overrides.serviceAccount || FLEET_SA,
    clusterRole: withPrefix(overrides.clusterRole, 'reader') || CLUSTER_ROLE,
    selfMintRole: withPrefix(overrides.selfMintRole, 'token-issuer') || SELF_MINT_ROLE,
  };
}

function documents({ names } = {}) {
  const {
    namespace: FLEET_NAMESPACE,
    serviceAccount: FLEET_SA,
    clusterRole: CLUSTER_ROLE,
    selfMintRole: SELF_MINT_ROLE,
  } = resolveNames(names);
  const docs = [
    {
      apiVersion: 'v1',
      kind: 'Namespace',
      metadata: { name: FLEET_NAMESPACE, labels }
    },
    {
      apiVersion: 'v1',
      kind: 'ServiceAccount',
      metadata: { name: FLEET_SA, namespace: FLEET_NAMESPACE, labels }
    },
    {
      apiVersion: 'rbac.authorization.k8s.io/v1',
      kind: 'ClusterRole',
      metadata: { name: CLUSTER_ROLE, labels },
      rules: readOnlyRules()
    },
    {
      apiVersion: 'rbac.authorization.k8s.io/v1',
      kind: 'ClusterRoleBinding',
      metadata: { name: CLUSTER_ROLE, labels },
      roleRef: { apiGroup: 'rbac.authorization.k8s.io', kind: 'ClusterRole', name: CLUSTER_ROLE },
      subjects: [{ kind: 'ServiceAccount', name: FLEET_SA, namespace: FLEET_NAMESPACE }]
    },
    // The hinge the renewal chain turns on. resourceNames pins it to fleet-reader's own
    // token endpoint: this account can renew itself and impersonate nothing.
    {
      apiVersion: 'rbac.authorization.k8s.io/v1',
      kind: 'Role',
      metadata: { name: SELF_MINT_ROLE, namespace: FLEET_NAMESPACE, labels },
      rules: [{ apiGroups: [''], resources: ['serviceaccounts/token'], resourceNames: [FLEET_SA], verbs: ['create'] }]
    },
    {
      apiVersion: 'rbac.authorization.k8s.io/v1',
      kind: 'RoleBinding',
      metadata: { name: SELF_MINT_ROLE, namespace: FLEET_NAMESPACE, labels },
      roleRef: { apiGroup: 'rbac.authorization.k8s.io', kind: 'Role', name: SELF_MINT_ROLE },
      subjects: [{ kind: 'ServiceAccount', name: FLEET_SA, namespace: FLEET_NAMESPACE }]
    }
  ];

  return docs;
}

function render({ names } = {}) {
  const { namespace: ns, serviceAccount: sa } = resolveNames(names);
  const header = [
    '# GENERATED by server/fleet/tools/print-rbac.js — do not edit by hand.',
    '#',
    '# What the Kyma Fleet Dashboard may do on this cluster. get/list/watch only on',
    '# resources, get on the discovery paths, plus the one namespaced right for',
    '# fleet-reader to mint its own successor token. No write verb on any cluster object.',
    '#',
    '#   kubectl apply -f fleet-dashboard-rbac.yaml',
    `#   kubectl create token ${sa} -n ${ns} --duration=24h`,
    '#',
    '# The second command prints the first token of the chain — paste it into the dashboard.',
    '# Everything after it is renewed at half-life by the dashboard itself, using the right',
    '# granted below. No workload is installed on this cluster.',
    ''
  ].join('\n');

  return header + documents({ names }).map(d => '---\n' + YAML.stringify(d)).join('');
}

function flag(argv, key) {
  const i = argv.indexOf(`--${key}`);
  return i === -1 ? undefined : argv[i + 1];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  process.stdout.write(render({
    names: {
      prefix: flag(process.argv, 'prefix'),
      namespace: flag(process.argv, 'namespace'),
      serviceAccount: flag(process.argv, 'sa'),
    },
  }));
}

export default { documents, render, resolveNames };
